export function translateAdminText(text: string, locale: AdminLocale): string {
  if (locale === 'en') return text;
  const trimmed = text.trim();
  const translation = translations[locale][trimmed] ?? translateDynamicAdminText(trimmed, locale);
  return translation === undefined
    ? text
    : `${text.slice(0, text.indexOf(trimmed))}${translation}${text.slice(text.indexOf(trimmed) + trimmed.length)}`;
}

export function translateCurrentAdminText(text: string): string {
  if (typeof document === 'undefined') return text;
  const locale = document.documentElement.lang;
  return translateAdminText(text, locale === 'ar' || locale === 'el' ? locale : 'en');
}

function translateDynamicAdminText(text: string, locale: Exclude<AdminLocale, 'en'>): string | undefined {
  const fileKey = text.match(/^Replace (.+)\?$/);
  if (fileKey) return locale === 'ar' ? `استبدال ${fileKey[1]}؟` : `Να αντικατασταθεί το ${fileKey[1]}?`;

  const deletionPrompt = text.match(/^Permanent deletion\. Type the full file key to confirm:\n([\s\S]+)$/);
  if (deletionPrompt) return locale === 'ar'
    ? `حذف نهائي. اكتب مفتاح الملف كاملًا للتأكيد:\n${deletionPrompt[1]}`
    : `Οριστική διαγραφή. Πληκτρολογήστε ολόκληρο το κλειδί αρχείου για επιβεβαίωση:\n${deletionPrompt[1]}`;

  const retired = text.match(/^Retire “(.+)” from the active directory\? You can restore it by editing its status\.$/);
  if (retired) return locale === 'ar'
    ? `إيقاف «${retired[1]}» من الدليل النشط؟ يمكنك استعادته بتعديل حالته.`
    : `Να αφαιρεθεί το «${retired[1]}» από τον ενεργό κατάλογο; Μπορείτε να το επαναφέρετε αλλάζοντας την κατάστασή του.`;

  const retiredNotice = text.match(/^(.+) retired\. Restore it by editing its status to active\.$/);
  if (retiredNotice) return locale === 'ar'
    ? `تم إيقاف ${retiredNotice[1]}. استعده بتغيير حالته إلى نشط.`
    : `Το ${retiredNotice[1]} απενεργοποιήθηκε. Επαναφέρετέ το αλλάζοντας την κατάστασή του σε ενεργό.`;

  const uploadNotice = text.match(/^Uploaded (.+)\.$/);
  if (uploadNotice) return locale === 'ar' ? `تم رفع ${uploadNotice[1]}.` : `Μεταφορτώθηκε το ${uploadNotice[1]}.`;
  const deleteNotice = text.match(/^Deleted (.+)\.$/);
  if (deleteNotice) return locale === 'ar' ? `تم حذف ${deleteNotice[1]}.` : `Διαγράφηκε το ${deleteNotice[1]}.`;

  const reportStatus = text.match(/^Report marked (.+)\.$/);
  if (reportStatus) {
    const status = translations[locale][reportStatus[1]] ?? reportStatus[1];
    return locale === 'ar' ? `تم وضع علامة على البلاغ: ${status}.` : `Η αναφορά σημειώθηκε ως ${status}.`;
  }
  return undefined;
}
