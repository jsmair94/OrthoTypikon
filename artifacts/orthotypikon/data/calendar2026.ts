function calendarDataKey(date: string) {
  const match = date.match(/^\d{4}-(\d{2})-(\d{2})$/);
  return match ? `2026-${match[1]}-${match[2]}` : date;
}

export function getCalendarEntry(date: string): CalendarEntry {
  return calendar2026[date] ?? { date, saints: [] };
}

export function shiftDateKey(date: string, days: number) {
  const value = new Date(`${date}T12:00:00Z`);
  value.setUTCDate(value.getUTCDate() + days);
  return value.toISOString().slice(0, 10);
}

export function getCalendarEntryForType(date: string, type: 'gregorian' | 'julian') {
  const dataKey = calendarDataKey(date);
  if (type === 'gregorian') {
    return (
      gregorianDailyCalendar2026[dataKey] ?? {
        date,
        saints: ['القديسون المذكورون في تقليد الكنيسة'],
      }
    );
  }
  return (
    julianCalendar2026[dataKey] ??
    calendar2026[shiftDateKey(dataKey, 13)] ??
    {
      date,
      saints: ['القديسون المذكورون في تقليد الكنيسة'],
    }
  );
}

export function getCalendarEntriesForType(type: 'gregorian' | 'julian') {
  if (type === 'gregorian') return Object.values(gregorianDailyCalendar2026);
  const shiftedLegacyEntries = Object.fromEntries(
    Object.values(calendar2026).map((entry) => {
      const date = shiftDateKey(entry.date, -13);
      return [date, { ...entry, date }];
    }),
  );
  return Object.values({ ...shiftedLegacyEntries, ...julianCalendar2026 });
}