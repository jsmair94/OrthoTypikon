const remainingJulianEntries = Object.fromEntries(
  Object.entries(julianDailyText2026).map(([date, text]) => {
    const feastLines: string[] = [];
    const saints: string[] = [];
    for (const line of text.split('\n').map((value) => value.trim()).filter(Boolean)) {
      if (julianFeastLinePattern.test(line)) feastLines.push(line);
      else saints.push(line);
    }
    return [date, { date, ...(feastLines.length ? { feast: feastLines.join('\n') } : {}), saints }];
  }),
) as Record<string, CalendarEntry>;

